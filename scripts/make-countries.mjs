#!/usr/bin/env node
/**
 * Regenerates src/data/countries.js, the table that turns a two-letter
 * country code into a country name for the Country filter. Codes come from
 * the `tvg-country` attribute or from the end of "Name.cc@Feed" style
 * channel ids ("CNN.us@SD" → "us").
 *
 * Names come from Node's own Unicode CLDR data (Intl.DisplayNames), so no
 * download is needed. The table is bundled rather than built on the TV
 * because webOS 4's Chromium 53 has no Intl.DisplayNames.
 *
 * Usage: node scripts/make-countries.mjs   (or: npm run countries)
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const names = new Intl.DisplayNames(['en'], { type: 'region', fallback: 'none' });

const table = {};
const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
for (const a of letters) {
  for (const b of letters) {
    const code = a + b;
    let name;
    try {
      name = names.of(code);
    } catch (e) {
      name = undefined;
    }
    // Skip unassigned codes and the macro-regions CLDR also names (EU, UN…) and the "Unknown Region" placeholder (ZZ).
    if (!name || name === code || ['EU', 'EZ', 'UN', 'QO', 'XA', 'XB', 'ZZ'].includes(code)) continue;
    table[code.toLowerCase()] = name;
  }
}
// Playlists often write "uk" for the United Kingdom (ISO uses "gb"), and
// "xk" for Kosovo; make sure both forms work.
if (table.gb) table.uk = table.gb;
if (!table.xk) table.xk = 'Kosovo';

const keys = Object.keys(table).sort();
const lines = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(table[k])},`);
const out = `/**
 * Country names by lower-case two-letter code, as found in \`tvg-country\`
 * attributes and at the end of "Name.cc@Feed" channel ids ("CNN.us@SD").
 * Generated by scripts/make-countries.mjs from Unicode CLDR data
 * (Intl.DisplayNames). Do not edit by hand.
 */
export const COUNTRIES = {
${lines.join('\n')}
};
`;
writeFileSync(join(root, 'src/data/countries.js'), out);
console.log(`Wrote src/data/countries.js (${keys.length} countries)`);
